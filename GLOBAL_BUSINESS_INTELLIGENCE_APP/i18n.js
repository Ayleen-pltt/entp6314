  function t(key) {
    return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  }

  function tf(key, vars) {
    let s = t(key);
    if (vars) {
      Object.keys(vars).forEach(k => { s = s.split("{" + k + "}").join(vars[k]); });
    }
    return s;
  }

  // Resolve a bilingual data field: {en:"...", es:"..."} -> current language string.
  // Falls back gracefully for plain strings so partially-translated data never breaks.
  function L(field) {
    if (field == null) return "";
    if (typeof field === "string") return field;
    if (typeof field === "object") return field[lang] || field.en || "";
    return String(field);
  }

  const READINESS_MAP = { GREEN: "readiness_green", YELLOW: "readiness_yellow", ORANGE: "readiness_orange", RED: "readiness_red" };
  function readinessLabel(code) {
    return READINESS_MAP[code] ? t(READINESS_MAP[code]) : code;
  }

  const LEVEL_MAP = { "Low": "level_low", "Medium": "level_medium", "High": "level_high", "Very Low": "level_very_low", "Very High": "level_very_high" };
  function levelText(word) {
    return LEVEL_MAP[word] ? t(LEVEL_MAP[word]) : word;
  }

  function getLang() { return lang; }

  function setLang(next) {
    if (next !== "en" && next !== "es") return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
    listeners.forEach(fn => fn(lang));
  }

  function onChange(fn) {
    listeners.push(fn);
  }

  return { t, tf, L, getLang, setLang, onChange, readinessLabel, levelText };

